"""GitHub access via the authenticated `gh` CLI (no token in files). Discovery + duplicate checking + AI-policy check."""
import json
import subprocess
import urllib.request


def _gh_api(path, params=None):
    # Force GET: `gh api` switches to POST as soon as any -f is passed.
    cmd = ["gh", "api", "-X", "GET", path]
    if params:
        for k, v in params.items():
            cmd += ["-f", f"{k}={v}"]
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, timeout=40)
        if out.returncode != 0:
            return None
        return json.loads(out.stdout)
    except (subprocess.TimeoutExpired, json.JSONDecodeError):
        return None


def discover_repos(lang="rust", min_stars=300, pushed_after="2025-06-01", limit=20):
    """Return [(full_name, stars, pushed_at)] for active, popular repos in `lang`.
    Deterministic filter — no LLM."""
    q = f"language:{lang} stars:>={min_stars} pushed:>={pushed_after} archived:false"
    d = _gh_api("search/repositories", {"q": q, "sort": "updated", "order": "desc", "per_page": str(limit)})
    if not d:
        return []
    return [(it["full_name"], it["stargazers_count"], it["pushed_at"]) for it in d.get("items", [])]


def head_commit(full_name):
    d = _gh_api(f"repos/{full_name}/commits", {"per_page": "1"})
    if d and isinstance(d, list) and d:
        return d[0]["sha"]
    return None


def ai_policy(full_name):
    """Check for an AI-contribution policy. Returns 'forbids' | 'ok' | 'unknown'.
    Fetches raw policy files (HTTP 200 only) and scans for disclosure/forbid language."""
    # Strong phrases only — avoid false positives on generic words.
    forbids_markers = [
        "ai-generated code", "ai generated code", "generated by ai", "llm-generated",
        "refrain from submitting", "fully-automated tools", "fully automated tools",
        "state so in your pr", "disclose.*ai", "must.*disclose", "no ai-generated",
        "ai-assisted contributions are not", "do not use ai", "prohibit.*ai",
    ]
    import re as _re
    for fname in ("AI_POLICY.md", "AGENTS.md", "CONTRIBUTING.md", ".github/CONTRIBUTING.md"):
        for branch in ("main", "master"):
            url = f"https://raw.githubusercontent.com/{full_name}/{branch}/{fname}"
            try:
                req = urllib.request.Request(url, headers={"User-Agent": "bugscout"})
                with urllib.request.urlopen(req, timeout=15) as r:
                    if r.status != 200:
                        continue
                    body = r.read(200_000).decode("utf-8", "ignore").lower()
            except Exception:
                continue
            if ("ai" in body or "llm" in body):
                if any(_re.search(m, body) for m in forbids_markers):
                    return "forbids"
                return "ok"  # mentions AI but no forbid language found
    return "unknown"


def is_duplicate(full_name, keywords):
    """Search open+closed issues AND PRs for the keywords. Returns (is_dup, ref_url).
    Deterministic dedup — no LLM."""
    kw = " ".join(keywords)
    q = f"repo:{full_name} {kw}"
    d = _gh_api("search/issues", {"q": q, "per_page": "5"})
    if not d:
        return False, ""
    items = d.get("items", [])
    if items:
        return True, items[0].get("html_url", "")
    return False, ""
